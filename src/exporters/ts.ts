/**
 * TypeScript exporter.
 *
 * For every table one module holding an interface describing the rows and a
 * constant holding the rows themselves, plus an index that re-exports them.
 */

import { camelCase, jsonText, pascalCase, slug } from './common.js';
import type { ExportFile } from './common.js';
import type { ExportView, GeneratedData } from './dataset.js';
import { tsType } from './common.js';
import type { Schema } from '../types.js';

export function exportTs(data: GeneratedData): ExportFile[] {
  const files: ExportFile[] = [];
  const index: string[] = ['// Generated by schema-seed.', ''];
  for (const view of data.views) {
    const moduleName = slug(view.name);
    const interfaceName = pascalCase(view.name) + 'Row';
    const constantName = camelCase(view.name) + 'Rows';
    files.push({ path: 'ts/' + moduleName + '.ts', content: module(view, interfaceName, constantName) });
    index.push(`export * from './${moduleName}.js';`);
  }
  files.push({ path: 'ts/index.ts', content: index.join('\n') + '\n' });
  return files;
}

/** One module: the interface and the data. */
function module(view: ExportView, interfaceName: string, constantName: string): string {
  const properties = (view.schema.properties ?? {}) as Record<string, Schema>;
  const required = new Set(Array.isArray(view.schema.required) ? (view.schema.required as string[]) : []);
  const lines: string[] = [];

  lines.push('// Generated by schema-seed — do not edit by hand.');
  lines.push('// Table: ' + view.name);
  lines.push('');
  lines.push('export interface ' + interfaceName + ' {');
  for (const property of Object.keys(properties)) {
    const schema = properties[property]!;
    let type = tsType(schema, 'unknown');
    const nullable =
      schema.nullable === true ||
      (Array.isArray(schema.type) && (schema.type as string[]).includes('null'));
    if (nullable) type += ' | null';
    const optional = required.has(property) ? '' : '?';
    lines.push('  ' + propertyKey(property) + optional + ': ' + type + ';');
  }
  lines.push('}');
  lines.push('');
  const body = jsonText(view.rows)
    .trimEnd()
    .split('\n')
    .map((line, index) => (index === 0 ? line : '  ' + line))
    .join('\n');
  lines.push('export const ' + constantName + ': ' + interfaceName + '[] = ' + body + ';');
  lines.push('');
  return lines.join('\n');
}

/** A property key that is valid TypeScript, quoted when it is not. */
function propertyKey(name: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);
}
